"""
preprocessing.py
================
Core of Algorithm 1 (Data Processing / Preprocessing).

What lives here
---------------
1. get_train_transforms() / get_val_transforms()
   Standard PyTorch transforms. These are THE transforms every model later
   (ViT, Swin, ConvNeXt, EfficientFormer) will reuse, so all models see
   exactly the same preprocessed data.

2. apply_enhancement(image, mode)
   Optional adverse-weather enhancement:
     - "clahe"   : contrast-limited adaptive histogram equalization
                   (helps fog / low-light / underexposed frames)
     - "denoise" : fast non-local means denoising (helps rain/snow grain)
     - "none"    : disabled (default for training)

3. BDDWeatherDataset
   torch.utils.data.Dataset that reads the manifest CSVs produced by
   build_dataset.py. One class for all models.

4. PreprocessingPipeline
   The JSON-friendly class the FastAPI backend will call later:
       pipe = PreprocessingPipeline()
       result = pipe.preprocess(image)   # -> JSON-ready dict
"""

import time
from pathlib import Path

import cv2
import numpy as np
import pandas as pd
import torch
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms

from . import config


# ---------------------------------------------------------------------------
# 1. Transforms (shared by all four models)
# ---------------------------------------------------------------------------
def get_train_transforms(input_size: int = config.INPUT_SIZE):
    """Augmentation pipeline for training.

    Mirrors the standard ImageNet recipe every torchvision pretrained
    transformer checkpoint expects: resize -> random crop -> flip ->
    colour jitter -> normalize with ImageNet mean/std.
    """
    return transforms.Compose([
        transforms.Resize(int(input_size * 1.14)),                  # 224 -> 256
        transforms.RandomResizedCrop(input_size, scale=(0.7, 1.0)),
        transforms.RandomHorizontalFlip(),
        transforms.ColorJitter(brightness=0.2, contrast=0.2,        # weather robustness
                               saturation=0.2, hue=0.05),
        transforms.ToTensor(),
        transforms.Normalize(config.IMAGENET_MEAN, config.IMAGENET_STD),
    ])


def get_val_transforms(input_size: int = config.INPUT_SIZE):
    """Deterministic pipeline for validation / testing (no augmentation)."""
    return transforms.Compose([
        transforms.Resize(int(input_size * 1.14)),
        transforms.CenterCrop(input_size),
        transforms.ToTensor(),
        transforms.Normalize(config.IMAGENET_MEAN, config.IMAGENET_STD),
    ])


# ---------------------------------------------------------------------------
# 2. Optional adverse-weather enhancement (off by default)
# ---------------------------------------------------------------------------
def apply_enhancement(image_bgr, mode: str = "none"):
    """Apply optional enhancement to a BGR image (OpenCV format).

    Returns (enhanced_image_bgr, mode_used).
    """
    if mode == "none":
        return image_bgr, "none"

    if mode == "clahe":
        # CLAHE on the L channel of LAB: lifts contrast in fog / low-light
        lab = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2LAB)
        l_chan, a_chan, b_chan = cv2.split(lab)
        clahe = cv2.createCLAHE(clipLimit=3.0, tileGridSize=(8, 8))
        l_chan = clahe.apply(l_chan)
        lab = cv2.merge((l_chan, a_chan, b_chan))
        return cv2.cvtColor(lab, cv2.COLOR_LAB2BGR), "clahe"

    if mode == "denoise":
        # Non-local means denoising: reduces rain/snow sensor noise
        denoised = cv2.fastNlMeansDenoisingColored(
            image_bgr, None, h=7, hColor=7,
            templateWindowSize=7, searchWindowSize=21,
        )
        return denoised, "denoise"

    raise ValueError(f"Unknown enhancement mode '{mode}' "
                     f"(choose 'none', 'clahe' or 'denoise').")


# ---------------------------------------------------------------------------
# 3. Dataset
# ---------------------------------------------------------------------------
def load_manifest(split: str) -> pd.DataFrame:
    """Load one manifest CSV (train / val / test) generated by build_dataset.py.

    Paths are made PORTABLE: earlier builds wrote absolute POSIX paths
    (e.g. /home/user/ADAS_testing/ADAS/datasets/Day/...). On a different machine
    those don't exist, so we rewrite each path relative to the *local*
    datasets/ directory. The manifest itself is left unchanged on disk.
    """
    csv_path = config.OUTPUT_DIR / f"manifest_{split}.csv"
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Manifest not found: {csv_path}\n"
            "Run build_dataset.py first (see ROADMAP / module README)."
        )
    df = pd.read_csv(csv_path)
    if "image_path" in df.columns:
        df["image_path"] = df["image_path"].map(_portable_path)
    # Drop rows pointing at junk sidecars or missing files (e.g. macOS
    # AppleDouble ._*.png, hidden/system metadata). These would otherwise crash
    # Image.open() mid-training and abort the whole run.
    keep = df["image_path"] if "image_path" in df.columns else df.index
    df = df[keep.map(_is_usable_path)]
    return df


# Names that are metadata/sidecar files, never real images.
_JUNK_MARKERS = ("._", ".ds_store", "thumbs.db", "desktop.ini", "@eadir")


def _is_usable_path(path: str) -> bool:
    """False for a junk sidecar path / a file that doesn't exist."""
    p = str(path)
    name = Path(p).name.lower()
    if name.startswith("._") or name.startswith("."):
        return False
    if any(m in name for m in _JUNK_MARKERS):
        return False
    return Path(p).exists()


def _portable_path(p: str) -> str:
    """Rewrite an absolute '<...>/datasets/<rel>' path to '<local>/datasets/<rel>'."""
    p = str(p)
    import re
    m = re.search(r"[\\/]datasets[\\/](.+)$", p)
    if m:
        return str(config.DATASETS_DIR / m.group(1))
    return p


class BDDWeatherDataset(Dataset):
    """PyTorch dataset built from a manifest CSV.

    One row -> one (image_tensor, label_index) pair.
    Every model (ViT, Swin, ConvNeXt, EfficientFormer) will use this same
    class with this same manifest, which guarantees identical data.
    """

    def __init__(self, split: str, transform=None, class_names=None):
        self.df = load_manifest(split)
        self.transform = transform
        self.class_names = class_names or config.WEATHER_CLASSES
        self.label_to_idx = {name: i for i, name in enumerate(self.class_names)}

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        path = row["image_path"]
        try:
            image = Image.open(path).convert("RGB")
        except Exception as e:
            # A single bad entry shouldn't abort the whole run; report it clearly
            # so the offending file can be removed.
            raise RuntimeError(
                f"Could not load dataset image: {path} ({type(e).__name__}: {e}). "
                "Remove or replace this file, then re-run prepare_current.py."
            ) from e
        if self.transform is not None:
            image = self.transform(image)
        label = self.label_to_idx[row["label"]]
        return image, label


# ---------------------------------------------------------------------------
# 4. PreprocessingPipeline (JSON-friendly, FastAPI-ready)
# ---------------------------------------------------------------------------
def tensor_to_image(tensor: torch.Tensor) -> np.ndarray:
    """Denormalize a [3,H,W] float tensor back to a 0..255 uint8 BGR image
    for visualization. (Only for display - models always use the tensor.)"""
    t = tensor.detach().cpu().clone()
    mean = torch.tensor(config.IMAGENET_MEAN).view(3, 1, 1)
    std = torch.tensor(config.IMAGENET_STD).view(3, 1, 1)
    t = t * std + mean                      # undo normalization
    t = t.clamp(0.0, 1.0) * 255.0
    t = t.permute(1, 2, 0).numpy().astype(np.uint8)
    return cv2.cvtColor(t, cv2.COLOR_RGB2BGR)


class PreprocessingPipeline:
    """End-to-end preprocessing.

    Later the FastAPI backend will simply do:

        from algorithms.preprocessing import PreprocessingPipeline
        pipe = PreprocessingPipeline()
        result = pipe.preprocess(image)     # -> JSON-ready dict

    Accepted inputs for `image`:
        - a path to an image file (str / Path)
        - a numpy BGR array (e.g. a frame from cv2.VideoCapture)
    """

    def __init__(self, input_size: int = config.INPUT_SIZE, enhance: str = "none"):
        self.input_size = input_size
        self.enhance = enhance
        self.val_transforms = get_val_transforms(input_size)

    # -- low-level: returns a real tensor (for the models) ------------------
    def preprocess_tensor(self, image):
        """BGR ndarray or path -> normalized [3, input_size, input_size] tensor."""
        bgr = self._load_image(image)
        enhanced, _ = apply_enhancement(bgr, self.enhance)
        rgb = cv2.cvtColor(enhanced, cv2.COLOR_BGR2RGB)
        return self.val_transforms(Image.fromarray(rgb))

    # -- high-level: returns the JSON contract ------------------------------
    def preprocess(self, image) -> dict:
        """Run the full pipeline and return a JSON-friendly dict:

        {
          "status": "success",
          "prediction": "preprocessed",
          "confidence": None,
          "inference_time_ms": ...,
          "results": { tensor_shape, tensor_mean, tensor_std, ... }
        }
        """
        t0 = time.perf_counter()
        bgr = self._load_image(image)
        h, w = bgr.shape[:2]

        enhanced, mode_used = apply_enhancement(bgr, self.enhance)
        rgb = cv2.cvtColor(enhanced, cv2.COLOR_BGR2RGB)
        tensor = self.val_transforms(Image.fromarray(rgb))

        dt_ms = (time.perf_counter() - t0) * 1000.0
        return {
            "status": "success",
            "prediction": "preprocessed",
            "confidence": None,
            "inference_time_ms": round(dt_ms, 3),
            "results": {
                "tensor_shape": list(tensor.shape),
                "tensor_dtype": str(tensor.dtype),
                "tensor_mean": round(float(tensor.mean()), 6),
                "tensor_std": round(float(tensor.std()), 6),
                "input_size": self.input_size,
                "original_size": [h, w],
                "enhancement": mode_used,
                "normalization": {
                    "mean": config.IMAGENET_MEAN,
                    "std": config.IMAGENET_STD,
                },
            },
        }

    def preprocess_batch(self, images) -> dict:
        """Preprocess a list of images; returns the stacked tensor + JSON dict."""
        t0 = time.perf_counter()
        tensors = [self.preprocess_tensor(img) for img in images]
        batch = torch.stack(tensors) if tensors else torch.empty(0)
        dt_ms = (time.perf_counter() - t0) * 1000.0
        return {
            "status": "success",
            "prediction": "preprocessed_batch",
            "confidence": None,
            "inference_time_ms": round(dt_ms, 3),
            "results": {
                "batch_size": len(images),
                "tensor_shape": list(batch.shape),
                "tensor_dtype": str(batch.dtype),
                "per_image_ms": round(dt_ms / max(len(images), 1), 3),
                "enhancement": self.enhance,
            },
        }

    @staticmethod
    def _load_image(image):
        """Accept a path or a numpy BGR array; always return a BGR ndarray."""
        if isinstance(image, (str, Path)):
            bgr = cv2.imread(str(image))
            if bgr is None:
                raise ValueError(f"Could not read image from: {image}")
            return bgr
        return image
